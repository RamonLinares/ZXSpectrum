export function parseBitmap(asciiLines) {
  return asciiLines.map(line => {
    const row = [];
    for (let i = 0; i < line.length; i++) {
      row.push(line[i] !== ' ' && line[i] !== '.' ? 1 : 0);
    }
    return row;
  });
}

