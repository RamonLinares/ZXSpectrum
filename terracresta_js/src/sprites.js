// Helper: Convert 16x16 or NxM ascii pattern string array into 2D boolean pixel matrix
export function parseBitmap(asciiLines) {
  return asciiLines.map(line => {
    const row = [];
    for (let i = 0; i < line.length; i++) {
      row.push(line[i] !== ' ' && line[i] !== '0' ? 1 : 0);
    }
    return row;
  });
}

